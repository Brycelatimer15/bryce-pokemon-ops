def normalize_cols(df: pd.DataFrame) -> pd.DataFrame:
    df = df.copy()
    df.columns = [str(c).strip() for c in df.columns]

    # Collectr export uses: "Market Price (As of YYYY-MM-DD)"
    for c in list(df.columns):
        if c.lower().startswith("market price (as of"):
            df = df.rename(columns={c: "Collectr Market Price"})
            break

    rename = {
        "Product": "Product Name",
        "Name": "Product Name",
        "Quantity": "Qty",
        "Average Cost Paid": "Avg Cost Paid",
        "Market Price": "Collectr Market Price",
        "Market Value": "Collectr Market Price",
        "Watchlist": "Collectr Watchlist",
    }
    for k, v in rename.items():
        if k in df.columns and v not in df.columns:
            df = df.rename(columns={k: v})

    return df

def to_number(series: pd.Series) -> pd.Series:
    s = series.astype(str).str.replace(r'[\$,]', '', regex=True).str.strip()
    return pd.to_numeric(s, errors="coerce").fillna(0.0)

def build_item_id(df: pd.DataFrame) -> pd.Series:
    if "ItemKey" in df.columns:
        return df["ItemKey"].astype(str)
    parts = []
    for c in ["Product Name","Set","Card #","Variant","Rarity","Grade","Condition"]:
        if c in df.columns:
            parts.append(df[c].astype(str).fillna("").str.strip())
    if not parts:
        return pd.Series(range(len(df))).astype(str)
    out = parts[0]
    for p in parts[1:]:
        out = out + "|" + p
    return out

def ebay_sold_link(name, set_name=None, card_no=None, variant=None, grade=None):
    q = str(name)
    for extra in [set_name, card_no, variant, grade]:
        if extra and str(extra).strip() and str(extra).strip().lower() != "nan":
            q += " " + str(extra)
    q = q.replace(" ", "+")
    return f"https://www.ebay.com/sch/i.html?_nkw={q}&LH_Sold=1&LH_Complete=1"

def tcg_link(name, set_name=None, card_no=None):
    q = str(name)
    for extra in [set_name, card_no]:
        if extra and str(extra).strip() and str(extra).strip().lower() != "nan":
            q += " " + str(extra)
    q = q.replace(" ", "+")
    return f"https://www.tcgplayer.com/search/pokemon/product?q={q}"

def compute(df: pd.DataFrame) -> pd.DataFrame:
    df = normalize_cols(df)

    if "Qty" not in df.columns: df["Qty"] = 1
    if "Avg Cost Paid" not in df.columns: df["Avg Cost Paid"] = 0
    if "Collectr Market Price" not in df.columns: df["Collectr Market Price"] = 0
    if "Price Override" not in df.columns: df["Price Override"] = 0

    df["Qty"] = to_number(df["Qty"])
    df["Avg Cost Paid"] = to_number(df["Avg Cost Paid"])
    df["Collectr Market Price"] = to_number(df["Collectr Market Price"])
    df["Price Override"] = to_number(df["Price Override"])

    df["Effective Price"] = np.where(df["Price Override"] > 0, df["Price Override"], df["Collectr Market Price"])
    df["Market Value (Total)"] = df["Effective Price"] * df["Qty"]
    df["Cost Basis (Total)"] = df["Avg Cost Paid"] * df["Qty"]

    df["Pack Cost Basis Value"] = np.where(df["Avg Cost Paid"] == 0, df["Market Value (Total)"], 0.0)
    total_basis = df["Pack Cost Basis Value"].sum()
    df["Allocated Pack Cost (Total)"] = np.where(
        (df["Avg Cost Paid"] == 0) & (total_basis > 0),
        (df["Pack Cost Basis Value"] / total_basis) * pack_spend,
        0.0
    )
    df["True Cost Basis (Total)"] = df["Cost Basis (Total)"] + df["Allocated Pack Cost (Total)"]

    df["Target Sell (Fast)"] = df["Effective Price"] * (1 - fast_discount)
    ship = np.where(df["Target Sell (Fast)"] <= 20, ship_pwe, ship_tracked)
    df["eBay Net/Unit (Fast)"] = (df["Target Sell (Fast)"] * (1 - ebay_fee)) - ship - supplies
    df["True eBay Profit (Total)"] = (df["eBay Net/Unit (Fast)"] * df["Qty"]) - df["True Cost Basis (Total)"]
    df["True eBay Margin %"] = np.where(
        (df["eBay Net/Unit (Fast)"] * df["Qty"]) > 0,
        df["True eBay Profit (Total)"] / (df["eBay Net/Unit (Fast)"] * df["Qty"]),
        0.0
    )

    df["Suggested Channel"] = np.where(df["Target Sell (Fast)"] <= 20, "Online (PWE)", "Online (Tracked)")
    df["Suggested Action"] = np.where(df["True eBay Profit (Total)"] >= min_profit, "LIST NOW", "HOLD / BUNDLE")

    name = df["Product Name"] if "Product Name" in df.columns else pd.Series(["(missing name)"]*len(df))
    setn = df["Set"] if "Set" in df.columns else pd.Series([""]*len(df))
    cardno = df["Card #"] if "Card #" in df.columns else pd.Series([""]*len(df))
    variant = df["Variant"] if "Variant" in df.columns else pd.Series([""]*len(df))
    grade = df["Grade"] if "Grade" in df.columns else pd.Series([""]*len(df))

    df["eBay Sold Comps"] = [ebay_sold_link(n, s, c, v, g) for n,s,c,v,g in zip(name, setn, cardno, variant, grade)]
    df["TCGplayer Search"] = [tcg_link(n, s, c) for n,s,c in zip(name, setn, cardno)]

    cond = df["Condition"].astype(str).str.lower() if "Condition" in df.columns else pd.Series([""]*len(df))
    looks_clean = ~cond.str.contains("hp|dam|dmg|played|crease|bend", na=False)
    df["Grade - Take a Look?"] = np.where((df["Effective Price"] >= grade_min_raw) & looks_clean, "TAKE A LOOK", "")

    return df

def kpi(a, b, c, d):
    col1, col2, col3, col4 = st.columns(4)
    col1.metric(a[0], a[1])
    col2.metric(b[0], b[1])
    col3.metric(c[0], c[1])
    col4.metric(d[0], d[1])

