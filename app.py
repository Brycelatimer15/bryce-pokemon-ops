def pct_change_days(days: int):
    cutoff = latest_date - pd.Timedelta(days=days)
    prev = history[history["SnapshotDate"] <= cutoff].sort_values("SnapshotDate").groupby("ItemID").tail(1)
    merged = latest.merge(prev[["ItemID","Effective Price"]], on="ItemID", how="left", suffixes=("","_prev"))
    merged[f"chg_{days}d"] = np.where(merged["Effective Price_prev"].notna() & (merged["Effective Price_prev"]>0),
                                     (merged["Effective Price"]/merged["Effective Price_prev"])-1,
                                     np.nan)
    return merged[["ItemID", f"chg_{days}d"]]

c30 = pct_change_days(30)
c60 = pct_change_days(60)
c90 = pct_change_days(90)

alerts = latest.merge(c30, on="ItemID", how="left").merge(c60, on="ItemID", how="left").merge(c90, on="ItemID", how="left")

def classify(row):
    for days,thr,label in [(90,-0.35,"SELL NOW"), (60,-0.25,"LIST SOON"), (30,-0.15,"WATCH")]:
        val = row.get(f"chg_{days}d")
        if pd.notna(val) and val <= thr:
            return label
    v30 = row.get("chg_30d")
    if pd.notna(v30) and v30 >= 0.30:
        return "SELL INTO HYPE"
    return ""

alerts["Trend Alert"] = alerts.apply(classify, axis=1)

